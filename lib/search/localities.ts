export function findLocality(name: string, cities: string[] = []): Locality | null {
    const wanted = name.trim().toLowerCase();
    const matches = LOCALITIES.filter((locality) =>
        locality.name.toLowerCase() === wanted || locality.aliases?.includes(wanted));
    if (!cities.length) return matches[0] ?? null;
    return matches.find((locality) => cities.includes(locality.city)) ?? null;
}
